<?php

use App\Actions\Audit\RecordAudit;
use App\Enums\AuditEvent;
use App\Enums\AuditResult;
use App\Exceptions\AuditLogIsAppendOnly;
use App\Models\AuditActivity;
use App\Models\User;
use Database\Seeders\DatabaseSeeder;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;

uses(RefreshDatabase::class);

function auditEntriesOf(string $event)
{
    return AuditActivity::query()->where('event', $event);
}

test('a successful sign-in is recorded with the account as actor and subject', function () {
    $user = User::factory()->create(['username' => 'rina.w']);

    $this->post(route('login.store'), ['login' => 'rina.w', 'password' => 'password']);

    $entry = auditEntriesOf('login')->sole();
    expect($entry->causer->is($user))->toBeTrue()
        ->and($entry->subject->is($user))->toBeTrue()
        ->and($entry->result)->toBe(AuditResult::Succeeded)
        ->and($entry->description)->toBe('Masuk');
});

test('a failed sign-in on a real account names the account but no actor and never the typed password', function () {
    $user = User::factory()->create(['username' => 'rina.w']);

    $this->post(route('login.store'), ['login' => 'rina.w', 'password' => 'tebakan-rahasia']);

    $entry = auditEntriesOf('login_failed')->sole();
    expect($entry->causer_id)->toBeNull()
        ->and($entry->subject->is($user))->toBeTrue()
        ->and($entry->result)->toBe(AuditResult::Failed)
        ->and(json_encode($entry->getAttributes()))->not->toContain('tebakan-rahasia');
});

test('a failed sign-in on an unknown account stores nothing that was typed', function () {
    $this->post(route('login.store'), ['login' => 'hantu.tak.dikenal', 'password' => 'tebakan-rahasia']);

    $entry = auditEntriesOf('login_failed')->sole();
    expect($entry->causer_id)->toBeNull()
        ->and($entry->subject_id)->toBeNull()
        ->and(json_encode($entry->getAttributes()))->not->toContain('hantu')->not->toContain('tebakan-rahasia');
});

test('a lockout is recorded once, not for every refused attempt', function () {
    foreach (range(1, 5) as $ignored) {
        $this->post(route('login.store'), ['login' => 'hantu', 'password' => 'salah-banget']);
    }
    $this->post(route('login.store'), ['login' => 'hantu', 'password' => 'salah-banget']);
    $this->post(route('login.store'), ['login' => 'hantu', 'password' => 'salah-banget']);

    expect(auditEntriesOf('login_failed')->count())->toBe(5)
        ->and(auditEntriesOf('lockout')->sole()->result)->toBe(AuditResult::Refused);
});

test('signing out is recorded', function () {
    $user = User::factory()->create();

    $this->actingAs($user)->post(route('logout'));

    expect(auditEntriesOf('logout')->sole()->causer->is($user))->toBeTrue();
});

test('every entry carries the request ID of the response and the IP address', function () {
    $response = $this->post(route('login.store'), ['login' => 'hantu', 'password' => 'salah-banget']);

    $entry = auditEntriesOf('login_failed')->sole();
    expect($entry->request_id)->toBe($response->headers->get('X-Request-Id'))
        ->and($entry->ip_address)->toBe('127.0.0.1');
});

test('the request ID is generated by the server and differs per request', function () {
    $first = $this->withHeader('X-Request-Id', 'dari-klien')->get(route('login'))->headers->get('X-Request-Id');
    $second = $this->get(route('login'))->headers->get('X-Request-Id');

    expect(Str::isUuid($first))->toBeTrue()->and($first)->not->toBe('dari-klien')->not->toBe($second);
});

test('creating a user is recorded with name, email, and username but hides the password', function () {
    $user = User::factory()->create(['username' => 'rina.w', 'name' => 'Rina Wulandari', 'email' => 'rina@example.test']);

    $entry = auditEntriesOf('created')->where('subject_id', $user->id)->sole();
    $attributes = $entry->attribute_changes['attributes'];
    expect($entry->description)->toBe('Pengguna dibuat')
        ->and($attributes['name'])->toBe('Rina Wulandari')
        ->and($attributes['email'])->toBe('rina@example.test')
        ->and($attributes['password'])->toBe('[disembunyikan]')
        ->and($attributes['username'])->toBe('rina.w');
});

test('changing a name records the old and new names', function () {
    $user = User::factory()->create(['name' => 'Nama Lama']);

    $user->update(['name' => 'Nama Baru']);

    $entry = auditEntriesOf('updated')->sole();
    expect($entry->description)->toBe('Pengguna diubah')
        ->and($entry->attribute_changes['old']['name'])->toBe('Nama Lama')
        ->and($entry->attribute_changes['attributes']['name'])->toBe('Nama Baru');
});

test('changing a username records the old and new values', function () {
    $user = User::factory()->create(['username' => 'lama']);

    $user->update(['username' => 'baru']);

    $entry = auditEntriesOf('updated')->sole();
    expect($entry->attribute_changes['old']['username'])->toBe('lama')
        ->and($entry->attribute_changes['attributes']['username'])->toBe('baru');
});

test('changing a password is recorded but neither the password nor its hash is stored', function () {
    $user = User::factory()->create();
    $oldHash = $user->password;

    $user->update(['password' => 'rahasia-baru-sekali']);

    $entry = auditEntriesOf('updated')->sole();
    expect($entry->attribute_changes['attributes']['password'])->toBe('[disembunyikan]')
        ->and(json_encode($entry->attribute_changes))
        ->not->toContain('rahasia-baru-sekali')
        ->not->toContain($oldHash)
        ->not->toContain($user->fresh()->password);
});

test('a change that only touches the timestamp or the remember token is not recorded', function () {
    $user = User::factory()->create();

    $user->touch();
    $user->forceFill(['remember_token' => 'token-baru'])->save();

    expect(auditEntriesOf('updated')->count())->toBe(0);
});

test('deleting and restoring a user are recorded', function () {
    $user = User::factory()->create();

    $user->delete();
    $user->restore();

    expect(auditEntriesOf('deleted')->sole()->description)->toBe('Pengguna dihapus')
        ->and(auditEntriesOf('restored')->sole()->description)->toBe('Pengguna dipulihkan');
});

test('a model change is attributed to the signed-in user', function () {
    $admin = User::factory()->create();
    $user = User::factory()->create(['username' => 'lama']);

    $this->actingAs($admin);
    $user->update(['username' => 'baru']);

    expect(auditEntriesOf('updated')->sole()->causer->is($admin))->toBeTrue();
});

test('an entry can be neither changed nor deleted by the application', function () {
    $entry = AuditActivity::query()->where('event', 'created')->firstOr(function () {
        User::factory()->create();

        return AuditActivity::query()->firstOrFail();
    });

    expect(fn () => $entry->update(['description' => 'diubah']))->toThrow(AuditLogIsAppendOnly::class)
        ->and(fn () => $entry->delete())->toThrow(AuditLogIsAppendOnly::class)
        ->and($entry->fresh()->description)->not->toBe('diubah');
});

test('an event outside a model change can be recorded with a subject, properties, and a result', function () {
    $user = User::factory()->create();

    app(RecordAudit::class)->handle(AuditEvent::Login, 'Contoh', causer: $user, subject: $user, properties: ['alasan' => 'uji'], result: AuditResult::Refused);

    $entry = auditEntriesOf('login')->sole();
    expect($entry->result)->toBe(AuditResult::Refused)
        ->and($entry->properties->all())->toBe(['alasan' => 'uji'])
        ->and($entry->subject->is($user))->toBeTrue();
});

test('retention deletes entries older than five years and keeps newer ones', function () {
    $row = fn (string $description, int $daysOld) => [
        'log_name' => 'audit',
        'description' => $description,
        'result' => 'succeeded',
        'created_at' => now()->subDays($daysOld),
        'updated_at' => now()->subDays($daysOld),
    ];
    DB::table('activity_log')->insert([$row('lama', 1827), $row('baru', 1825)]);

    $this->artisan('activitylog:clean', ['--force' => true])->assertSuccessful();

    expect(AuditActivity::query()->pluck('description')->all())->toBe(['baru']);
});

test('the retention command is scheduled', function () {
    $this->artisan('schedule:list')->expectsOutputToContain('activitylog:clean')->assertSuccessful();
});

test('seeding does not write audit entries', function () {
    config(['app.seed_demo_accounts' => true]);

    $this->seed(DatabaseSeeder::class);

    expect(AuditActivity::query()->count())->toBe(0);
});

test('authentication events belong to the Autentikasi module and model changes to their own', function () {
    User::factory()->create(['username' => 'rina.w']);

    $this->post(route('login.store'), ['login' => 'rina.w', 'password' => 'password']);

    expect(auditEntriesOf('login')->sole()->log_name)->toBe('Autentikasi')
        ->and(auditEntriesOf('created')->sole()->log_name)->toBe('Pengguna');
});

test('an entry keeps the method, path, and user agent of its request but never the query string', function () {
    $this->withHeader('User-Agent', 'UjiBrowser/1.0')
        ->post(route('login.store').'?token=rahasia', ['login' => 'hantu', 'password' => 'salah-banget']);

    $entry = auditEntriesOf('login_failed')->sole();
    expect($entry->method)->toBe('POST')
        ->and($entry->path)->toBe('/login')
        ->and($entry->user_agent)->toBe('UjiBrowser/1.0')
        ->and(json_encode($entry->getAttributes()))->not->toContain('rahasia');
});
